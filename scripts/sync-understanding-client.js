#!/usr/bin/env node
'use strict';

/**
 * Sync chatre1/public/{understanding,analyst}.js from this API repo.
 * No new serverless routes — local maintainer script only.
 *
 * Usage: node scripts/sync-understanding-client.js [/path/to/chatre1]
 */

const fs = require('fs');
const path = require('path');

const apiRoot = path.join(__dirname, '..');
const clientRoot = path.resolve(
  process.argv[2] || path.join(apiRoot, '..', 'chatre1'),
);

function syncUnderstanding() {
  let src = fs.readFileSync(path.join(apiRoot, 'lib/understanding.js'), 'utf8');
  src = src.replace(/^['"]use strict['"];\s*/m, '');
  const exportMatch = src.match(/\nmodule\.exports\s*=\s*\{([\s\S]*?)\};\s*$/);
  if (!exportMatch) throw new Error('understanding.js: module.exports not found');
  src = src.slice(0, exportMatch.index);

  const names = [
    'CONFIDENCE_THRESHOLD',
    'SOFT_DONE_PATTERNS',
    'VALID_TASK_TYPES',
    'isSoftDoneWhen',
    'isHowToQuestion',
    'softTaskTypeHint',
    'classifyDeliverableKind',
    'extractPaths',
    'extractIntentSignals',
    'preLlmRoute',
    'enrichFromSignals',
    'validateBriefingSchema',
    'filterBlockingUnknowns',
    'isBlockingUnknown',
    'isNonBlockingUnknown',
    'applyUnderstandingGate',
    'resolveTaskType',
    'compileDoneWhen',
    'suggestMode',
    'formatIntentContract',
    'mergeCorrections',
    'applyCorrectionsWithRescore',
    'scoreRouter',
    'detectCorrectionMessage',
    'detectClarifyFeedback',
    'isProceedDirective',
    'isWorkspaceDirective',
    'isRepoDirective',
    'isIncrementalFollowUp',
    'correctDesignTypos',
    'expandFollowUpMessage',
    'seedBriefingFromPrior',
    'inferDefaultFiles',
    'guessProjectSlug',
    'answerFirstDoNot',
    'asStringList',
    'clamp01',
    'loadCorrections',
    'saveCorrection',
    'rememberIfCorrection',
    'correctionsKey',
    'persistDurableCorrections',
  ];

  const clientHelpers = `
function correctionsKey(threadId) {
  return 'chatre_corrections_' + String(threadId || 'local');
}

function loadCorrections(threadId) {
  try {
    const raw = sessionStorage.getItem(correctionsKey(threadId));
    const list = raw ? JSON.parse(raw) : [];
    return asStringList(list);
  } catch (e) {
    return [];
  }
}

function saveCorrection(threadId, text) {
  const msg = String(text || '').trim();
  if (!msg) return loadCorrections(threadId);
  let list = loadCorrections(threadId);
  if (list.indexOf(msg) < 0) list.unshift(msg);
  list = list.slice(0, 16);
  try {
    sessionStorage.setItem(correctionsKey(threadId), JSON.stringify(list));
  } catch (e) {
    /* ignore */
  }
  return list;
}

function rememberIfCorrection(text, threadId) {
  const detected = detectCorrectionMessage(text);
  if (!detected) return loadCorrections(threadId);
  return saveCorrection(threadId, detected);
}

function persistDurableCorrections(threadId, corrections) {
  const tid = String(threadId || '').trim();
  const list = asStringList(corrections);
  if (!tid || !list.length) return Promise.resolve(list);
  list.forEach(function (c) {
    saveCorrection(tid, c);
  });
  try {
    if (window.ChatreRemote && window.ChatreRemote.updateThread) {
      return window.ChatreRemote.updateThread(tid, {
        durableCorrections: loadCorrections(tid),
      }).then(function () {
        return loadCorrections(tid);
      }).catch(function () {
        return loadCorrections(tid);
      });
    }
  } catch (e) {
    /* ignore */
  }
  return Promise.resolve(loadCorrections(tid));
}
`;

  const out =
    '/**\n' +
    ' * Message-understanding precision (client mirror of chatre-api/lib/understanding.js).\n' +
    ' * Generated by scripts/sync-understanding-client.js — do not hand-edit behavior.\n' +
    ' */\n' +
    '(function () {\n' +
    '  "use strict";\n\n' +
    src
      .split('\n')
      .map((line) => (line.length ? '  ' + line : ''))
      .join('\n') +
    '\n' +
    clientHelpers
      .split('\n')
      .map((line) => (line.length ? '  ' + line : ''))
      .join('\n') +
    '\n\n  window.ChatreUnderstanding = {\n' +
    names.map((n) => '    ' + n + ': ' + n + ',').join('\n') +
    '\n  };\n' +
    '})();\n';

  const dest = path.join(clientRoot, 'public/understanding.js');
  fs.writeFileSync(dest, out);
  return dest;
}

function syncAnalyst() {
  let body = fs.readFileSync(path.join(apiRoot, 'lib/analyst.js'), 'utf8');
  body = body.replace(/^['"]use strict['"];\s*/m, '');
  body = body.replace(
    /const Understanding = require\('\.\/understanding'\);/g,
    'const Understanding = window.ChatreUnderstanding;',
  );
  const exp = body.match(/\nmodule\.exports\s*=\s*\{([\s\S]*?)\};\s*$/);
  if (!exp) throw new Error('analyst.js: module.exports not found');
  body = body.slice(0, exp.index);

  const runAnalysis = `
  async function runAnalysis(userMessage, options) {
    const opts = options || {};
    const Understanding = window.ChatreUnderstanding;
    if (Understanding && Understanding.preLlmRoute) {
      const route = Understanding.preLlmRoute(userMessage);
      if (route && route.skipAnalyst) {
        return normalizeBriefing(
          {
            understanding: 'Greeting / short chat.',
            goal: String(userMessage || '').slice(0, 120),
            task_type: route.task_type || 'chat',
            deliverable_kind: route.deliverable_kind || 'answer',
            confidence: route.confidence || 0.95,
            needs_clarification: false,
            clarification_question: '',
            suggested_mode: route.suggested_mode || 'chat',
            mode_reason: route.reason || 'short greeting',
            success_criteria: [],
            done_when: 'User has a friendly reply',
            files: [],
            approach: [],
            todos: [],
            tools_priority: [],
            do_not: ['Do not create workspace files for a greeting'],
            constraints: [],
            executor_brief: 'Reply briefly and warmly. No tools.',
            max_steps: 1,
          },
          userMessage,
          {
            composerMode:
              opts.composerMode ||
              (window.ChatreComposer && window.ChatreComposer.getMode
                ? window.ChatreComposer.getMode()
                : 'agent'),
            corrections: opts.corrections,
          },
        );
      }
    }
    const signal = opts.signal;
    const model =
      opts.model || '@cf/meta/llama-3.3-70b-instruct-fp8-fast';
    const history = opts.history || [];
    const snippet = historySnippet(history);
    const response = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      signal: signal,
      body: JSON.stringify({
        model: model,
        stream: false,
        agent: false,
        mode: 'analyst',
        max_tokens: 2048,
        messages: [
          {
            role: 'user',
            content: analystUserPrompt(userMessage, snippet, {
              corrections: opts.corrections,
              composerMode:
                opts.composerMode ||
                (window.ChatreComposer && window.ChatreComposer.getMode
                  ? window.ChatreComposer.getMode()
                  : undefined),
            }),
          },
        ],
      }),
    });
    if (!response.ok) {
      throw new Error('Analyst HTTP ' + response.status);
    }
    const data = await response.json();
    const text = (data && (data.response || data.text)) || '';
    const parsed = extractJsonObject(text);
    return normalizeBriefing(parsed, userMessage, {
      corrections: opts.corrections,
      composerMode:
        opts.composerMode ||
        (window.ChatreComposer && window.ChatreComposer.getMode
          ? window.ChatreComposer.getMode()
          : 'agent'),
    });
  }
`;

  const out =
    '/**\n' +
    ' * Chatre analyst — client mirror of chatre-api/lib/analyst.js.\n' +
    ' * Generated by scripts/sync-understanding-client.js — do not hand-edit behavior.\n' +
    ' */\n' +
    '(function () {\n' +
    '  "use strict";\n\n' +
    body
      .split('\n')
      .map((line) => (line.length ? '  ' + line : ''))
      .join('\n') +
    '\n' +
    runAnalysis +
    '\n  window.ChatreAnalyst = {\n' +
    '    ANALYST_SYSTEM_PROMPT: ANALYST_SYSTEM_PROMPT,\n' +
    '    ANALYST_FEW_SHOTS: ANALYST_FEW_SHOTS,\n' +
    '    extractJsonObject: extractJsonObject,\n' +
    '    normalizeBriefing: normalizeBriefing,\n' +
    '    formatExecutorPrompt: formatExecutorPrompt,\n' +
    '    analystUserPrompt: analystUserPrompt,\n' +
    '    historySnippet: historySnippet,\n' +
    '    runAnalysis: runAnalysis,\n' +
    '  };\n' +
    '})();\n';

  const dest = path.join(clientRoot, 'public/analyst.js');
  fs.writeFileSync(dest, out);
  return dest;
}

const u = syncUnderstanding();
const a = syncAnalyst();
console.log('Synced:\n ', u, '\n ', a);
